#!/usr/bin/env python3
"""Draw the Inkling icon: a wide chisel-tip highlighter, held below the line it drew.

Writes the extension icon (public/logo.svg), the components favicon and the
Logo.svelte component. `make icons` runs this and renders the PNG sizes from
logo.svg. Change the shape through the parameters below, never by editing the
generated files.

The pen is drawn upright with the tip pointing down (+y), tilted by ANGLE, and
then mirrored top to bottom, so the pen ends up below the line it drew. The
ink line spans exactly the chisel edge, so it is as wide as the tip.
"""

import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXTENSION_SVG = HERE.parent / 'public' / 'logo.svg'
COMPONENTS = HERE.parent.parent / 'components'
FAVICON_SVG = COMPONENTS / 'static' / 'favicon.svg'
LOGO_SVELTE = COMPONENTS / 'src' / 'lib' / 'logos' / 'Logo.svelte'

INK = '#FFD60A'  # tip, cap and the line on the paper
BODY = '#3E7CB1'  # keeps the pen readable on dark toolbars
OUTLINE = 22  # stroke width of all outlines

BODY_HALF_WIDTH = 98
TIP_HALF_WIDTH = 80
ANGLE = 56  # pen tilt from vertical, degrees
CHISEL_SLANT = 20  # angle of the chisel edge across the tip, degrees
CHISEL_SHORT_SIDE = 36
COLLAR_LENGTH = 40
BODY_LENGTH = 150
CAP_LENGTH = 110
BAND_HEIGHT = 34
LINE_LENGTH = 1.7  # length of the ink line, in multiples of its width


def fmt(v):
	return f'{v:.1f}'


def path(points):
	return 'M' + ' L'.join(f'{fmt(x)} {fmt(y)}' for x, y in points) + ' Z'


def draw(outline, band):
	"""Return (viewBox, ink line, pen elements); outline and band are color values."""
	b, t = BODY_HALF_WIDTH, TIP_HALF_WIDTH
	a = math.radians(ANGLE)

	def rotate(x, y):
		return (x * math.cos(a) - y * math.sin(a), x * math.sin(a) + y * math.cos(a))

	tip_top = COLLAR_LENGTH
	edge_top = COLLAR_LENGTH + CHISEL_SHORT_SIDE
	drop = 2 * t * math.tan(math.radians(CHISEL_SLANT))
	tip = [(-t, tip_top), (t, tip_top), (t, edge_top + drop), (-t, edge_top)]
	collar = [(-b, 0), (b, 0), (t + 6, tip_top), (-t - 6, tip_top)]
	cap_end = -BODY_LENGTH - CAP_LENGTH + 10

	# The ink line runs left from the chisel edge and is exactly as tall as it.
	e1, e2 = rotate(-t, edge_top), rotate(t, edge_top + drop)
	top, bottom = sorted([e1, e2], key=lambda p: p[1])
	width = bottom[1] - top[1]
	start = min(e1[0], e2[0]) - width * LINE_LENGTH
	r = width / 2

	# Fit everything into a square with a margin, so nothing is cut off.
	corners = [(-b - 4, cap_end), (b + 4, cap_end), (b + 4, -BODY_LENGTH), (-b - 4, -BODY_LENGTH)]
	points = [rotate(x, y) for x, y in tip + collar + corners]
	points += [(start, top[1]), (start, bottom[1])]
	pad = OUTLINE / 2 + 6
	xs, ys = [p[0] for p in points], [p[1] for p in points]
	min_x, max_x, min_y, max_y = min(xs) - pad, max(xs) + pad, min(ys) - pad, max(ys) + pad
	size = max(max_x - min_x, max_y - min_y) * 1.06
	cx, cy = (min_x + max_x) / 2, (min_y + max_y) / 2
	view_box = f'{fmt(cx - size / 2)} {fmt(-cy - size / 2)} {fmt(size)} {fmt(size)}'

	line = (
		f'M{fmt(top[0])} {fmt(top[1])} H{fmt(start + r)} '
		f'a{fmt(r)} {fmt(r)} 0 0 0 0 {fmt(width)} H{fmt(bottom[0])} Z'
	)
	pen = [
		f'<path d="{path(tip)}" fill="{INK}" />',
		f'<path d="{path(collar)}" fill="{BODY}" />',
		f'<rect x="{-b}" y="{-BODY_LENGTH}" width="{2 * b}" height="{BODY_LENGTH + 2}" rx="14" fill="{BODY}" />',
		f'<rect x="{-b - 4}" y="{cap_end}" width="{2 * b + 8}" height="{CAP_LENGTH}" rx="30" fill="{INK}" />',
		f'<rect x="{-b - 4}" y="{-BODY_LENGTH - 30}" width="{2 * b + 8}" height="{BAND_HEIGHT}" fill="{band}" />',
	]
	group = f'<g transform="rotate({ANGLE})" stroke="{outline}" stroke-width="{OUTLINE}" stroke-linejoin="round">'
	return view_box, f'<path d="{line}" fill="{INK}" />', group, pen


def svg_file():
	view_box, line, group, pen = draw('#000', '#000')
	body = '\n\t\t'.join(pen)
	return (
		f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}" width="512" height="512">\n'
		'<!-- Inkling icon, generated by packages/extension/scripts/icon.py (make icons). -->\n'
		'<g transform="scale(1 -1)">\n'
		f'\t{line}\n'
		f'\t{group}\n\t\t{body}\n\t</g>\n'
		'</g>\n</svg>\n'
	)


def svelte_file():
	view_box, line, group, pen = draw('currentcolor', 'currentcolor')
	body = '\n\t\t\t'.join(pen)
	return (
		'<script lang="ts">\n'
		"export let width = '100%';\n"
		"export let height = '100%';\n"
		'</script>\n\n'
		'<!-- Inkling logo, generated by packages/extension/scripts/icon.py (make icons).\n'
		'     The outline follows the text color, so it works on light and dark pages. -->\n'
		'<svg\n'
		'\t{width}\n'
		'\t{height}\n'
		f'\tviewBox="{view_box}"\n'
		'\txmlns="http://www.w3.org/2000/svg"\n'
		'\tclass="dark:text-white text-black"\n'
		'>\n'
		'\t<g transform="scale(1 -1)">\n'
		f'\t\t{line}\n'
		f'\t\t{group}\n\t\t\t{body}\n\t\t</g>\n'
		'\t</g>\n'
		'</svg>\n'
	)


if __name__ == '__main__':
	EXTENSION_SVG.write_text(svg_file())
	FAVICON_SVG.write_text(svg_file())
	LOGO_SVELTE.write_text(svelte_file())
	for p in (EXTENSION_SVG, FAVICON_SVG, LOGO_SVELTE):
		print(f'wrote {p}')
